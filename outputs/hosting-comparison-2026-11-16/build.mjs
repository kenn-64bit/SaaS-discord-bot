import fs from 'node:fs/promises';
import path from 'node:path';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';

const outputDir = path.dirname(new URL(import.meta.url).pathname);
const data = JSON.parse(await fs.readFile(path.join(outputDir, 'research.json'), 'utf8'));
const workbook = Workbook.create();
const sheet = workbook.worksheets.add('Hosting shortlist');
sheet.showGridLines = false;
sheet.tabColor = '#263D58';
const last = 11 + data.rows.length;
sheet.getRange(`A1:K${last}`).format.font = { name: 'Arial', size: 10, color: '#243447' };
sheet.getRange(`A1:K${last}`).format.verticalAlignment = 'center';
sheet.getRange(`A1:K${last}`).format.rowHeight = 24;
sheet.getRange('A2').values = [['Discord bot hosting shortlist']];
sheet.getRange('A2').format.font = { name: 'Arial', size: 16, bold: true, color: '#263D58' };
sheet.getRange('A3:K3').format.borders = { bottom: { style: 'thin', color: '#9AA8B8' } };
sheet.getRange('A4').values = [['Monthly budget (PHP)']];
sheet.getRange('B4').values = [[1200]];
sheet.getRange('C4').values = [['Planning PHP / USD']];
sheet.getRange('D4').values = [[65]];
sheet.getRange('E4').values = [['Tax + bank reserve']];
sheet.getRange('F4').values = [[0.2]];
sheet.getRange('G4').values = [['Checked 16 Nov 2026']];
sheet.getRange('A5').values = [['Estimates = USD × rate × (1 + reserve). Reserve is a planning allowance, not a quoted tax rate.']];
sheet.getRange('A5').format.font.italic = true;
sheet.getRange('A6').values = [['Yellow cells are editable. Use Status and My notes to track your choice. Filter the header row.']];
sheet.getRange('A7').values = [[data.winner]];
sheet.getRange('A7').format.font = { name:'Arial', size:11, bold:true, color:'#263D58' };
sheet.getRange('A8').values = [[data.fit]];
sheet.getRange('A9').values = [[data.scope]];
for (const cell of ['B4','D4','F4']) sheet.getRange(cell).format.fill = '#FFF0C2';
sheet.getRange('B4').format.numberFormat = '"₱"#,##0';
sheet.getRange('D4').format.numberFormat = '0.00';
sheet.getRange('F4').format.numberFormat = '0%';
const headers = ['Provider / plan','Category','Monthly USD','Budget PHP','Budget check','Always online?','Setup','Status','My notes','Limits / free-tier terms','Official sources'];
sheet.getRange('A11:K11').values = [headers];
const rows = data.rows.map(r => [r.provider,r.category,r.usd,null,null,r.online,r.setup,r.status||'To review',r.notes||'',r.limits,r.sources.join('\n')]);
sheet.getRange(`A12:K${last}`).values = rows;
for (let i=0; i<rows.length; i++) {
  const row=12+i;
  sheet.getRange(`D${row}`).formulas = [[`=IF(C${row}="","n.a.",ROUND(C${row}*$D$4*(1+$F$4),0))`]];
  sheet.getRange(`E${row}`).formulas = [[`=IF(D${row}="n.a.","Check terms",IF(D${row}>$B$4,"Over budget",IF(B${row}="Paid variable","Minimum only","Within budget")))`]];
}
const table = sheet.tables.add(`A11:K${last}`, true, 'HostingOptions');
table.showFilterButton = true;
sheet.getRange('A11:K11').format = { fill:'#263D58',font:{name:'Arial',size:10,color:'#FFFFFF',bold:true},horizontalAlignment:'center',verticalAlignment:'center',wrapText:true,rowHeight:34 };
sheet.getRange(`A12:K${last}`).format.wrapText = true;
sheet.getRange(`A12:K${last}`).format.rowHeight = 60;
sheet.getRange(`A12:K${last}`).format.fill = '#FFFFFF';
for (let row=12; row<=last; row+=2) sheet.getRange(`A${row}:K${row}`).format.fill = '#F0F4F8';
sheet.getRange(`A12:K${last}`).format.verticalAlignment = 'top';
sheet.getRange(`C12:D${last}`).format.horizontalAlignment = 'right';
sheet.getRange(`E12:E${last}`).format.horizontalAlignment = 'center';
sheet.getRange(`C12:C${last}`).format.numberFormat = '"$"0.00';
sheet.getRange(`D12:D${last}`).format.numberFormat = '"₱"#,##0';
sheet.getRange(`H12:I${last}`).format.fill = '#FFF7DF';
sheet.getRange(`H12:H${last}`).dataValidation = {rule:{type:'list',values:['To review','Shortlisted','Testing','Chosen','On hold','Rejected']}};
sheet.getRange(`D12:D${last}`).conditionalFormats.add('cellIs',{operator:'greaterThan',formula:'$B$4',format:{fill:'#FFE1DE',font:{color:'#9D2921',bold:true}}});
sheet.getRange(`H12:H${last}`).conditionalFormats.add('containsText',{text:'Chosen',format:{fill:'#DCEBDD',font:{color:'#285A33',bold:true}}});
sheet.getRange(`H12:H${last}`).conditionalFormats.add('containsText',{text:'Rejected',format:{fill:'#EEEEEE',font:{color:'#6A6A6A'}}});
sheet.getRange(`H12:H${last}`).conditionalFormats.add('containsText',{text:'On hold',format:{fill:'#FFE1DE',font:{color:'#9D2921',bold:true}}});
const widths = { A:27,B:15,C:14,D:14,E:15,F:21,G:12,H:16,I:28,J:69,K:76 };
for (const [col,width] of Object.entries(widths)) sheet.getRange(`${col}1:${col}${last}`).format.columnWidth = width;
sheet.freezePanes.freezeRows(11);
sheet.freezePanes.freezeColumns(1);
workbook.recalculate();

const costs = sheet.getRange(`D12:D${last}`).values.map(r=>r[0]);
data.rows.forEach((row,i) => {
  if (typeof row.usd === 'number' && costs[i] !== Math.round(row.usd*65*1.2)) throw new Error(`Cost check failed for ${row.provider}: ${costs[i]}`);
});
const numericRow = data.rows.findIndex(r=>typeof r.usd==='number' && r.usd>0)+12;
const base = sheet.getRange(`D${numericRow}`).values[0][0];
sheet.getRange('D4').values = [[70]];
workbook.recalculate();
const changed = sheet.getRange(`D${numericRow}`).values[0][0];
if (base === changed) throw new Error('Exchange-rate input did not recalculate costs');
sheet.getRange('B4').values = [[1]];
workbook.recalculate();
if (sheet.getRange(`E${numericRow}`).values[0][0] !== 'Over budget') throw new Error('Budget boundary did not update');
sheet.getRange('D4').values = [[65]];
sheet.getRange('B4').values = [[1200]];
workbook.recalculate();
console.log((await workbook.inspect({kind:'table',range:`'Hosting shortlist'!A11:H${last}`,include:'values,formulas',tableMaxRows:14,tableMaxCols:8,maxChars:5500})).ndjson);
console.log((await workbook.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#N/A|#NUM!|#NULL!|#SPILL!|#CALC!',options:{useRegex:true,maxResults:20},summary:'Final formula error scan',maxChars:1500})).ndjson);
for (const [name, range] of [['overview','A1:J'+last],['sources','J11:K'+last]]) {
  const preview = await workbook.render({sheetName:sheet.name,range,scale:1,format:'png'});
  await fs.writeFile(path.join(outputDir,name+'.png'), new Uint8Array(await preview.arrayBuffer()));
}
const xlsx = await SpreadsheetFile.exportXlsx(workbook);
await xlsx.save(path.join(outputDir,'discord-bot-hosting-shortlist.xlsx'));
console.log(JSON.stringify({output:path.join(outputDir,'discord-bot-hosting-shortlist.xlsx'),rows:data.rows.length,inputTest:{base,changed},costs}));
